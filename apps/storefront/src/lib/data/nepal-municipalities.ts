/** Lowercase letters only — spaces, hyphens and other separators ignored. */
function normalizeDistrictName(name: string): string {
  return name
    .trim()
    .toLowerCase()
    .replace(/[^a-z]/g, "");
}

/**
 * Backend district name → source district name (both normalized).
 *
 * The checkout district list comes from the backend (`Spree::District`,
 * official English spellings) while this dataset uses the reference
 * spelling, which differs for a few districts:
 * - Panchthar (backend) ↔ Pachthar (source)
 * - Tanahun ↔ Tanahu, Kapilvastu ↔ Kapilbastu
 * - Nawalpur ↔ Nawalparasi East, Parasi ↔ Nawalparasi West
 */
const DISTRICT_ALIASES: Record<string, string> = {
  panchthar: "pachthar",
  tanahun: "tanahu",
  nawalpur: "nawalparasieast",
  // Legacy typo in an earlier revision of this dataset ("Nawalparari East").
  nawalpararieast: "nawalparasieast",
  kapilvastu: "kapilbastu",
  parasi: "nawalparasiwest",
};

const DISTRICT_INDEX: Map<string, NepalLocalLevel[]> = new Map(
  Object.entries(DISTRICT_DATA).map(([name, levels]) => [
    normalizeDistrictName(name),
    levels,
  ]),
);

function dedupeByName(levels: NepalLocalLevel[]): NepalLocalLevel[] {
  const seen = new Set<string>();
  return levels.filter((level) => {
    const key = level.name_en.toLowerCase();
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

/**
 * Local levels for a backend district name. Returns [] for blank/unknown
 * districts — callers fall back to a free-text city input so checkout is
 * never blocked by a data gap.
 */
export function getMunicipalitiesForDistrict(
  districtName: string | null | undefined,
): NepalLocalLevel[] {
  if (!districtName) return [];
  const normalized = normalizeDistrictName(districtName);
  if (!normalized) return [];
  const direct = DISTRICT_INDEX.get(normalized);
  if (direct) return dedupeByName(direct);
  const aliased = DISTRICT_ALIASES[normalized];
  if (aliased) {
    const found = DISTRICT_INDEX.get(aliased);
    if (found) return dedupeByName(found);
  }
  return [];
}

/**
 * Dropdown label for a local level. Both scripts are always included so the
 * searchable combobox matches English and Nepali queries; the current
 * locale decides which script leads.
 */
export function formatMunicipalityOption(
  level: NepalLocalLevel,
  locale?: string,
): string {
  if (locale?.toLowerCase().startsWith("ne")) {
    return `${level.name_ne} (${level.type_ne}) · ${level.name_en}`;
  }
  return `${level.name_en} (${level.type_en}) · ${level.name_ne}`;
}

/** Number of districts covered — useful for tests and health checks. */
export function municipalityDistrictCount(): number {
  return DISTRICT_INDEX.size;
}
